-- Watch Together: invitation links are random UUIDs, but access is also
-- restricted to the host and users who joined through the invitation function.
create table if not exists public.watch_rooms (
  id uuid primary key default gen_random_uuid(),
  host_user_id uuid not null references auth.users(id) on delete cascade,
  media_type text not null check (media_type in ('movie', 'tv')),
  tmdb_id bigint not null check (tmdb_id > 0),
  season_number integer not null default 1 check (season_number > 0),
  episode_number integer not null default 1 check (episode_number > 0),
  position_seconds integer not null default 0 check (position_seconds between 0 and 86400),
  is_playing boolean not null default false,
  playback_revision bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 hours')
);

create table if not exists public.watch_room_members (
  room_id uuid not null references public.watch_rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (room_id, user_id)
);

create index if not exists watch_room_members_user_idx on public.watch_room_members (user_id);

alter table public.watch_rooms enable row level security;
alter table public.watch_room_members enable row level security;
revoke all on table public.watch_rooms, public.watch_room_members from anon, authenticated;
grant select, insert, update on table public.watch_rooms to authenticated;
grant select on table public.watch_room_members to authenticated;

drop policy if exists "Room members can read their membership" on public.watch_room_members;
create policy "Room members can read their membership"
  on public.watch_room_members for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Hosts and members can read rooms" on public.watch_rooms;
create policy "Hosts and members can read rooms"
  on public.watch_rooms for select to authenticated
  using (
    expires_at > now() and (
      host_user_id = (select auth.uid())
      or exists (
        select 1 from public.watch_room_members m
        where m.room_id = id and m.user_id = (select auth.uid())
      )
    )
  );

drop policy if exists "Hosts can create rooms" on public.watch_rooms;
create policy "Hosts can create rooms"
  on public.watch_rooms for insert to authenticated
  with check (host_user_id = (select auth.uid()));

drop policy if exists "Only hosts can update rooms" on public.watch_rooms;
create policy "Only hosts can update rooms"
  on public.watch_rooms for update to authenticated
  using (host_user_id = (select auth.uid()) and expires_at > now())
  with check (host_user_id = (select auth.uid()));

