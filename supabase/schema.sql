create or replace function public.join_watch_room(room_id uuid)
returns boolean language plpgsql security definer set search_path = '' as $$
declare
  current_user_id uuid := (select auth.uid());
begin
  if current_user_id is null then return false; end if;
  if not exists (
    select 1 from public.watch_rooms
    where id = room_id and expires_at > now()
  ) then return false; end if;
  insert into public.watch_room_members (room_id, user_id)
  values (room_id, current_user_id)
  on conflict do nothing;
  return true;
end;
$$;
revoke all on function public.join_watch_room(uuid) from public, anon;
grant execute on function public.join_watch_room(uuid) to authenticated;

