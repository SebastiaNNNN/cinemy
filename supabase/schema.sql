-- Persistent party lobby. An invite is valid for two minutes; joining members
-- remain in the party after that invite expires. All playback writes are host-only.
create table if not exists public.watch_parties (
  id uuid primary key default gen_random_uuid(),
  host_user_id uuid not null references auth.users(id) on delete cascade,
  media_type text check (media_type in ('movie', 'tv')),
  tmdb_id bigint check (tmdb_id > 0),
  season_number integer not null default 1 check (season_number > 0),
  episode_number integer not null default 1 check (episode_number > 0),
  position_seconds integer not null default 0 check (position_seconds between 0 and 86400),
  is_playing boolean not null default false,
  playback_revision bigint not null default 0,
  member_count integer not null default 0 check (member_count between 0 and 4),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  playback_updated_at timestamptz not null default now(),
  ended_at timestamptz,
  constraint party_media_pair check ((media_type is null) = (tmdb_id is null))
);

create table if not exists public.watch_party_members (
  party_id uuid not null references public.watch_parties(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (party_id, user_id)
);

create table if not exists public.watch_party_invites (
