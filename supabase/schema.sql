create or replace function public.join_watch_party(p_token uuid)
returns uuid language plpgsql security definer set search_path = '' as $$
declare
  joining_user uuid := (select auth.uid());
  target_party uuid;
  party_host uuid;
  already_member boolean;
begin
  if joining_user is null then raise exception 'Sign in to join a party'; end if;
  select i.party_id into target_party from public.watch_party_invites i
    where i.token = p_token and i.expires_at > now();
  if target_party is null then raise exception 'Invite expired or invalid'; end if;
  select p.host_user_id into party_host from public.watch_parties p
    where p.id = target_party and p.ended_at is null for update;
  if party_host is null then raise exception 'Party unavailable'; end if;
  if party_host = joining_user then raise exception 'The host cannot join their own invite'; end if;
  select exists(select 1 from public.watch_party_members m where m.party_id = target_party and m.user_id = joining_user)
    into already_member;
  if not already_member then
    if (select p.member_count from public.watch_parties p where p.id = target_party) >= 4 then
      raise exception 'Party is full';
    end if;
    insert into public.watch_party_members (party_id, user_id) values (target_party, joining_user);
    update public.watch_parties set member_count = member_count + 1 where id = target_party;
  end if;
  return target_party;
end;
$$;
revoke all on function public.join_watch_party(uuid) from public, anon;
grant execute on function public.join_watch_party(uuid) to authenticated;

create or replace function public.leave_watch_party(p_party_id uuid)
returns boolean language plpgsql security definer set search_path = '' as $$
declare
  leaving_user uuid := (select auth.uid());
  removed_count integer;
begin
  if leaving_user is null then return false; end if;
  perform 1 from public.watch_parties where id = p_party_id for update;
  delete from public.watch_party_members where party_id = p_party_id and user_id = leaving_user;
  get diagnostics removed_count = row_count;
  if removed_count > 0 then
    update public.watch_parties set member_count = greatest(0, member_count - 1) where id = p_party_id;
  end if;
  return removed_count > 0;
end;
$$;
revoke all on function public.leave_watch_party(uuid) from public, anon;
grant execute on function public.leave_watch_party(uuid) to authenticated;

