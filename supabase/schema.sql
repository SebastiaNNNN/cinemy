create table if not exists public.watch_history (
  id bigint generated by default as identity primary key,
  media_id text unique not null,
  title text not null,
  poster_path text,
  backdrop_path text,
  progress_seconds integer not null default 0 check (progress_seconds >= 0),
  duration_seconds integer not null default 0 check (duration_seconds >= 0),
  updated_at timestamptz not null default now()
);

create index if not exists watch_history_updated_at_idx
  on public.watch_history (updated_at desc);

alter table public.watch_history enable row level security;

-- Aplicația accesează tabela numai prin ruta server-side /api/progress.
-- Cheia service role nu trebuie expusă niciodată în browser.
revoke all on table public.watch_history from anon, authenticated;
